import assert from "node:assert/strict";
import test from "node:test";
import { buildRestoreSql, orderBackupFiles } from "../scripts/restore-backup.mjs";

test("orderBackupFiles places parent tables before children and skips storage/audit", () => {
  const ordered = orderBackupFiles([
    "ypl_schema_validation.matches.json",
    "ypl_schema_validation.seasons.json",
    "ypl_schema_validation.events.json",
    "public.site_data.json",
    "storage.board.json",
    "ypl_audit.change_log.json",
    "README.txt",
  ]);
  assert.deepEqual(ordered, [
    "public.site_data.json",
    "ypl_schema_validation.seasons.json",
    "ypl_schema_validation.events.json",
    "ypl_schema_validation.matches.json",
  ]);
});

test("buildRestoreSql generates transactional jsonb_populate_recordset statements safely", () => {
  const { sql, totalRows } = buildRestoreSql([
    { table: "public.site_data", rows: [{ key: "ypl_data_v4", value: { note: "contains $ypl_json$" } }] },
    { table: "ypl_schema_validation.seasons", rows: [] },
  ]);
  assert.equal(totalRows, 1);
  assert.match(sql, /^-- Generated by scripts\/restore-backup\.mjs/);
  assert.match(sql, /begin;/);
  assert.match(sql, /insert into public\.site_data/);
  assert.match(sql, /\$ypl_json_1\$/);
  assert.match(sql, /on conflict do nothing;/);
  assert.match(sql, /commit;/);
  assert.doesNotMatch(sql, /ypl_schema_validation\.seasons/);
});
