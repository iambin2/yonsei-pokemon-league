const RIGHT_FACING = new Set(RIGHT_FACING_SLUGS);

export function spriteSlugFromUrl(src) {
  return /\/sprites\/pokemon(?:-s)?\/([^/?#]+)\.webp/.exec(String(src || ""))?.[1] || "";
}

export function facesRight(srcOrSlug) {
  const s = String(srcOrSlug || "");
  return RIGHT_FACING.has(s.includes("/") ? spriteSlugFromUrl(s) : s);
}

export function actorFlipped(own, srcOrSlug) {
  return Boolean(own) !== facesRight(srcOrSlug);
}
