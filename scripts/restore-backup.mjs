const ORDER_INDEX = new Map(RESTORE_ORDER.map((name, i) => [name, i]));
const IDENT = /^[a-z_][a-z0-9_]*\.[a-z_][a-z0-9_]*$/;

export function orderBackupFiles(files) {
  return [...files]
    .filter(f => f.endsWith(".json") && !f.startsWith("storage.") && !f.startsWith("ypl_audit."))
    .sort((a, b) => {
      const ka = a.replace(/\.json$/, "");
      const kb = b.replace(/\.json$/, "");
      const ia = ORDER_INDEX.has(ka) ? ORDER_INDEX.get(ka) : 9999;
      const ib = ORDER_INDEX.has(kb) ? ORDER_INDEX.get(kb) : 9999;
      return ia - ib || ka.localeCompare(kb);
    });
}

function dollarTag(text) {
  let tag = "$ypl_json$";
  let n = 0;
  while (text.includes(tag)) tag = `$ypl_json_${++n}$`;
  return tag;
}

export function buildRestoreSql(entries) {
  const lines = [
    "-- Generated by scripts/restore-backup.mjs",
    "-- Review before running in Supabase SQL Editor. Wrapped in a transaction with ON CONFLICT DO NOTHING.",
    "begin;",
    "",
  ];
  let totalRows = 0;
  for (const { table, rows } of entries) {
    if (!IDENT.test(table)) throw new Error(`Invalid table name: ${table}`);
    if (!Array.isArray(rows) || !rows.length) continue;
    totalRows += rows.length;
    const json = JSON.stringify(rows);
    const tag = dollarTag(json);
    lines.push(`-- ${table}: ${rows.length} rows`);
    lines.push(`insert into ${table}`);
    lines.push(`select * from jsonb_populate_recordset(null::${table}, ${tag}${json}${tag}::jsonb)`);
    lines.push("on conflict do nothing;");
    lines.push("");
  }
  lines.push("commit;");
  lines.push("");
  return { sql: lines.join("\n"), totalRows };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  let dir = "";
  let onlyTable = "";
  let outFile = "";
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--table" && args[i + 1]) onlyTable = args[++i];
    else if (args[i] === "--out" && args[i + 1]) outFile = args[++i];
    else if (!args[i].startsWith("--") && !dir) dir = args[i];
  }
  if (!dir) {
    console.error("Usage: npm run restore:plan -- <backup-dir> [--table schema.table] [--out restore.sql]");
    process.exit(1);
  }
  const files = orderBackupFiles(readdirSync(dir))
    .filter(f => !onlyTable || f === `${onlyTable}.json`);
  const entries = files.map(f => ({
    table: basename(f, ".json"),
    rows: JSON.parse(readFileSync(join(dir, f), "utf8")),
  }));
  const { sql, totalRows } = buildRestoreSql(entries);
  if (outFile) {
    writeFileSync(outFile, sql, "utf8");
    console.log(`Wrote ${outFile} (${entries.length} tables checked, ${totalRows} rows).`);
  } else {
    process.stdout.write(sql);
  }
}
