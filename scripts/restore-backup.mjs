// Generates a foreign-key-ordered PostgreSQL restore SQL script from an unpacked YPL backup directory.
// Usage:
//   npm run restore:plan -- <backup-dir> [--table schema.table] [--out restore.sql]
// The output uses jsonb_populate_recordset with ON CONFLICT DO NOTHING inside a single transaction.
